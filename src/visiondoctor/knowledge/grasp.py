BY_ID = {card.id: card for card in CARDS}


def catalogue() -> list[dict[str, str]]:
    return [{"id": card.id, "title": card.title} for card in CARDS]


def read_knowledge(knowledge_ids: list[str]) -> dict[str, Any]:
    if not 1 <= len(knowledge_ids) <= 3:
        raise ValueError("一次选择 1 至 3 个领域")
    unknown = set(knowledge_ids) - BY_ID.keys()
    if unknown:
        raise ValueError(f"unknown knowledge: {', '.join(sorted(unknown))}")
    return {
        "kind": "domain_guidance",
        "basis": "通用工程原理整理；具体工位约定、参数和阈值须由项目证据确认。",
        "cards": [asdict(BY_ID[key]) for key in dict.fromkeys(knowledge_ids)],
        "limits": "知识说明如何检查，不是本案观察，不能代替 evidence_id 支持排除或根因。",
    }
